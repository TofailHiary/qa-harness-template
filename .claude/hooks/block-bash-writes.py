#!/usr/bin/env python3
"""PreToolUse Bash - READ-ONLY QA (portable).

Policy, from harness-config.json (generated by /configure-project):
  protected_repos  folder names of product source repositories -> no writes of any kind
  owned_repos      folder names of the team's own tooling repos -> git/npm writes allowed there,
                   but ONLY when no protected repo is in reach (cwd, cd target, git -C, or a path)

Guards (all regex-based; see scripts/hook-redteam for the qualification suite):
  1. git is an ALLOW-LIST of read-only verbs. Anything not proven read-only is refused
     (fetch/pull are deliberately allowed so /sync-repos can bring repos to the commit under test).
     Every shell segment is checked (`git status; git commit` does not pass).
  2. npm publish / version / ci are refused.
  3. With a protected repo in reach: redirection, tee, sed -i, dd, rm -r, mv/cp into it,
     write verbs (touch, mkdir, install, patch, truncate, ln, rsync, unzip, ...), writing forms of
     curl/wget/tar/npm/pip/npx/docker, interpreter writes (python -c "open(...,'w')", node -e
     writeFileSync, ...), and a redirect after `cd` into it or while cwd is inside it.
  4. Heredoc BODIES fed to a non-shell interpreter are DATA and are not scanned (a markdown file
     written through `python - <<PY` that merely mentions a git verb must not be blocked).
Reads stay allowed: a guard that blocks `docker ps` or `git log` gets switched off, and a
switched-off guard protects nothing. Fail-closed on malformed hook input.
"""
import json
import re
import sys
import harness_config as hc

CFG = hc.load()
SRC_DIRS = CFG.get("protected_repos", [])
OWNED_DIRS = CFG.get("owned_repos", [])


def _alt(names):
    if not names:
        return None
    return r"(?<![A-Za-z0-9_.-])(" + "|".join(re.escape(d) for d in names) + r")(?![A-Za-z0-9_-])"


SRC_ALT = _alt(SRC_DIRS)
OWNED_ALT = _alt(OWNED_DIRS)

MUTATING_NPM_VERBS = ["publish", "version", "ci"]


def _block(reason):
    sys.stdout.write(json.dumps({"decision": "block", "reason": reason}))
    sys.exit(2)


def _read_cmd():
    try:
        raw = sys.stdin.read()
        if not raw.strip():
            _block("READ-ONLY QA: empty Bash hook input. Blocked.")
        data = json.loads(raw)
    except Exception as e:
        _block("READ-ONLY QA: could not parse Bash hook input (" + type(e).__name__ + "). Blocked.")
        return ("", "")
    return ((data.get("tool_input", {}) or {}).get("command", "") or "",
            data.get("cwd") or "")


def _in_src(text):
    return bool(SRC_ALT and re.search(SRC_ALT, text, re.IGNORECASE))


def owned_context(cmd_norm, cwd):
    """True when the command runs inside an OWNED repo and names no protected repo."""
    if not OWNED_ALT:
        return False
    cwd_norm = (cwd or "").replace(chr(92), "/")
    if _in_src(cmd_norm) or _in_src(cwd_norm):
        return False                      # a protected repo is in reach: no exemption
    if re.search(r"/" + OWNED_ALT + r"(?:/|$)", cwd_norm, re.IGNORECASE):
        return True
    if re.search(r"(?:^|[;&|])\s*(?:cd|pushd)\s+[^;&|]*/" + OWNED_ALT + r"(?:/|\s|$)", cmd_norm, re.IGNORECASE):
        return True
    if re.search(r"git\s+(?:-C|--git-dir=|--work-tree=)\s*[^\s]*/" + OWNED_ALT + r"(?:/|\s|$|\.git)", cmd_norm, re.IGNORECASE):
        return True
    return False


_SHELLS = ("bash", "sh", "zsh", "dash", "ksh", "eval", "source")
_EXEC_STDIN = ("python", "python3", "node", "perl", "ruby", "php")


def strip_heredoc_bodies(cmd, keep_interp=False):
    """Remove heredoc BODIES so text inside a document is not read as a command.

    A heredoc body piped into cat/python/node is DATA for the git/npm scan: prose that merely mentions
    a git verb must not be blocked. Bodies fed to a SHELL are left in place - those really do execute.
    With keep_interp=True the bodies fed to an interpreter (python - <<PY ...) are kept too, so the
    interpreter-write scan can still see an open(..., "w") inside them.
    """
    spans = []
    for m in re.finditer(r"<<-?\s*([\'\"]?)([A-Za-z_][A-Za-z0-9_]*)\1", cmd):
        head = cmd[:m.start()]
        launcher = head.rsplit("|", 1)[-1].rsplit(";", 1)[-1].strip().split()
        piped_to_interp = bool(re.search(r"\|\s*(?:env\s+)?(python[0-9.]*|node|perl|ruby|php|bash|sh)\b", cmd))
        first = launcher[0] if launcher else ""
        if first == "env" and len(launcher) > 1:
            first = launcher[1]          # `env python - <<PY` - the real launcher is next
        if piped_to_interp:
            continue                     # body is a PROGRAM: keep it, do not strip
        if launcher and first.endswith(tuple(_SHELLS)):
            continue
        if keep_interp and launcher and first.endswith(tuple(_EXEC_STDIN)):
            continue
        delim = m.group(2)
        end = re.search(r"^" + re.escape(delim) + r"$", cmd[m.end():], re.M)
        if not end:
            continue
        spans.append((m.end(), m.end() + end.start()))
    if not spans:
        return cmd
    kept, prev = [], 0
    for s, e in spans:
        kept.append(cmd[prev:s])
        prev = e
    kept.append(cmd[prev:])
    return "".join(kept)


# Git: ALLOW-LIST, not blacklist. A blacklist reopens reset --soft / stash push / branch / tag /
# config / notes add / worktree add the moment one entry is removed.
GIT_READ_VERBS = {
    "log", "show", "diff", "status", "rev-parse", "rev-list", "ls-tree", "ls-files", "ls-remote",
    "cat-file", "blame", "describe", "shortlog", "grep", "merge-base", "merge-tree", "name-rev",
    "for-each-ref", "count-objects", "check-ignore", "whatchanged", "var", "version", "help",
    # fetch/pull are DELIBERATELY allowed: /sync-repos exists to bring repos to the commit under
    # test. They move refs and the working tree, but that is the documented workflow.
    "fetch", "pull",
}
# Verbs whose BARE form writes (a bare stash is a stash push).
GIT_BARE_WRITES = {"stash"}
# Verbs that are read-only ONLY in their listing form.
GIT_LIST_ONLY = {
    "branch": ("-a", "-r", "-v", "-vv", "--list", "--contains", "--merged", "--no-merged", "--show-current", "--format"),
    "tag": ("-l", "--list", "--contains", "--points-at", "--format"),
    "stash": ("list", "show"),
    "worktree": ("list",),
    "notes": ("list", "show"),
    "submodule": ("status", "summary", "foreach"),
    "remote": ("-v", "show", "get-url"),
    "reflog": ("show",),
    "bisect": ("log", "view"),
    "symbolic-ref": ("--short", "-q"),
    "archive": (),
    "config": ("--get", "--get-all", "--list", "-l", "--get-regexp", "--show-origin"),
}


def check_git(cmd):
    # Only inspecting the first git invocation lets `git status; git commit` pass. Check EVERY segment.
    for seg in re.split(r"(?:&&|\|\||;|\n)", cmd):
        _check_git_one(seg)


def _check_git_one(cmd):
    """Block any git invocation whose verb is not provably read-only."""
    # `git` must be a command token: not part of a path such as `./.git -prune` (a dot before it).
    m = re.search(r"(?i)(?:^|[^A-Za-z.])git\s+((?:-[A-Za-z]+(?:\s+\S+)?\s+|--[A-Za-z-]+(?:=[^\s]+)?\s+)*)([A-Za-z][A-Za-z-]*)(.*)", cmd)
    if not m:
        return                      # bare 'git', 'git --version' etc.
    verb = m.group(2).lower()
    rest = (m.group(3) or "").strip()
    if verb in GIT_LIST_ONLY:
        toks = rest.split()
        first = toks[0] if toks else ""
        if (not rest and verb not in GIT_BARE_WRITES) or any(first == f or rest.startswith(f) for f in GIT_LIST_ONLY[verb]):
            return
        _block("READ-ONLY QA: git %s is read-only only in its listing form; %r writes. Blocked."
               % (verb, (first or rest)[:30]))
    if verb not in GIT_READ_VERBS:
        _block("READ-ONLY QA: git %s is not on the read-only allow-list, so it is blocked. "
               "Read-only git (log/show/diff/status/branch -a/...) stays available." % verb)


def check_npm(cmd):
    for sub in MUTATING_NPM_VERBS:
        if re.search(r"(?i)(?:^|[^A-Za-z])npm\s+" + sub + r"(?![A-Za-z-])", cmd):
            _block("READ-ONLY QA: npm " + sub + " is blocked.")


def check_writes(cmd_norm):
    if not SRC_ALT or not re.search("/" + SRC_ALT + r"(?:/|$|\s|[^A-Za-z0-9_-])", cmd_norm, re.IGNORECASE):
        return
    into = "/(?:" + "|".join(re.escape(d) for d in SRC_DIRS) + ")"
    if re.search(r">>?\s*[^|<>\n]*" + into, cmd_norm, re.IGNORECASE):
        _block("READ-ONLY QA: Bash redirection into a protected repo is blocked.")
    if re.search(r"\|\s*tee\b", cmd_norm, re.IGNORECASE):
        _block("READ-ONLY QA: tee with a protected repo path is blocked.")
    if re.search(r"(?:^|[^A-Za-z])sed\s+-i", cmd_norm, re.IGNORECASE):
        _block("READ-ONLY QA: sed -i with a protected repo path is blocked.")
    if re.search(r"(?:^|[^A-Za-z])dd\s+[^|]*of=", cmd_norm, re.IGNORECASE):
        _block("READ-ONLY QA: dd of= with a protected repo path is blocked.")
    if re.search(r"(?:^|[^A-Za-z])rm\s+(-[rRfF]+)", cmd_norm):
        _block("READ-ONLY QA: rm -r/-rf touching a protected repo is blocked.")
    if re.search(r"(?:^|[^A-Za-z])mv\s+[^|]+\s+[^\s]*" + into, cmd_norm, re.IGNORECASE):
        _block("READ-ONLY QA: mv into a protected repo is blocked.")
    if re.search(r"(?:^|[^A-Za-z])cp\s+[^|]+\s+[^\s]*" + into, cmd_norm, re.IGNORECASE):
        _block("READ-ONLY QA: cp into a protected repo is blocked.")


def check_cwd_and_interpreter_writes(cmd, cmd_norm):
    """Two escapes: `cd <repo>` then a relative redirect; and an interpreter write (`python -c`
    with open(...,'w')) at any path form. READS STAY ALLOWED."""
    if not SRC_ALT:
        return
    cd_src = re.search(r"(?:^|[;&|])\s*cd\s+[^;&|]*" + SRC_ALT, cmd_norm, re.IGNORECASE)
    wverb = re.search(
        r"(>>?[^>]|(?:^|[^A-Za-z])tee\b|(?:^|[^A-Za-z])sed\s+-i"
        r"|(?:^|[^A-Za-z])dd\s+[^|]*of="
        r"|(?:^|[^A-Za-z])rm\s+-[rRfF]"
        r"|(?:^|[^A-Za-z])(?:mv|cp|touch|mkdir)\s)", cmd_norm)
    if cd_src and wverb:
        _block("READ-ONLY QA: a write verb after cd into a protected repo is blocked. Reads stay allowed.")

    interp = re.search(r"(?:^|[^A-Za-z])(python[0-9.]*|node|perl|ruby|php)\s+(-c|-e|-p)\b", cmd_norm, re.IGNORECASE)
    if interp and _in_src(cmd_norm):
        pieces = [r"open\s*\([^)]*[\x22\x27][wax]", "writeFileSync", "appendFileSync",
                  "createWriteStream", r"\.write\s*\(", "WriteAllText", "Set-Content",
                  r"os\.(remove|rename)"]
        if re.search("|".join(pieces), cmd, re.IGNORECASE):
            _block("READ-ONLY QA: interpreter write into a protected repo is blocked. "
                   "Use the memory dir or qa-evidence.")


# Two classes, because command NAME alone is not evidence of a write: name-only matching false-blocks
# curl GET, docker ps, tar -tf, sed -n and pip show whenever cwd happens to be a repo.
ALWAYS_WRITE = ["tee", "truncate", "install", "patch", "shred", "ln", "rsync", "dd",
                "cp", "mv", "mkdir", "touch", "rm", "chmod", "chown", "unzip"]

# name -> regex that must ALSO match before we treat it as a write.
CONDITIONAL_WRITE = {
    "curl":   r"""(?:^|[\s'"])(-o\b|-O\b|--output\b|--remote-name\b)|\|\s*(python|node|sh|bash|perl)""",
    "wget":   r"(?:^|\s)(-O\b|--output-document\b|-P\b|--directory-prefix\b)",
    "tar":    r"(?:^|\s)-{0,2}[A-Za-z]*x[A-Za-z]*\b|--extract\b",
    "sed":    r"""(?:^|[\s'"])-[A-Za-z]*i""",
    "perl":   r"(?:^|\s)-[A-Za-z]*i[A-Za-z]*\b",
    "docker": r"(?:^|\s)(cp\b|exec\b)",
    "npm":    r"(?:^|\s)(install\b|i\b|ci\b|publish\b|link\b|--prefix\b)",
    "pnpm":   r"(?:^|\s)(install\b|add\b|publish\b)",
    "yarn":   r"(?:^|\s)(install\b|add\b|publish\b)",
    "npx":    r".",
    "pip":    r"(?:^|\s)(install\b|uninstall\b|download\b)",
    "pip3":   r"(?:^|\s)(install\b|uninstall\b|download\b)",
}

# Interpreters: a write CALL inside the payload is the signal, not the interpreter itself.
INTERP = r"(?:^|[^A-Za-z0-9_./-])(python[0-9.]*|node|perl|ruby|php|pwsh|powershell)(?:\s|$)"
INTERP_WRITE = r"(?:open\s*\([^)]*[\x22\x27][wax]|writeFileSync|appendFileSync|createWriteStream|\.write\s*\(|WriteAllText|Set-Content|Out-File|os\.(?:remove|rename|unlink)|shutil\.(?:copy|move))"

NO_WRITE_FLAGS = r"(?:^|\s)(--dry-run|--help|--version)(?=\s|$)"


def _writes_into_src(cmd_norm, cwd):
    """Is a protected repo in reach - by explicit path, or because cwd is inside one?"""
    if cwd and _in_src(cwd.replace(chr(92), "/")):
        return True
    return _in_src(cmd_norm)


def check_write_verb_near_src(cmd, cmd_norm, cwd):
    """Block WRITES in reach of a protected repo. Reads must keep working."""
    if not SRC_ALT or not _writes_into_src(cmd_norm, cwd):
        return
    if re.search(NO_WRITE_FLAGS, cmd_norm, re.IGNORECASE):
        return  # a dry-run / help / version invocation writes nothing, whatever the verb

    for v in ALWAYS_WRITE:
        if re.search(r"(?:^|[^A-Za-z0-9_./-])" + re.escape(v) + r"(?![A-Za-z0-9_-])", cmd_norm, re.IGNORECASE):
            _block("READ-ONLY QA: %s writes, and a protected repo is in reach. Blocked." % v)

    for v, needs in CONDITIONAL_WRITE.items():
        if not re.search(r"(?:^|[^A-Za-z0-9_./-])" + re.escape(v) + r"(?![A-Za-z0-9_-])", cmd_norm, re.IGNORECASE):
            continue
        tail = cmd_norm.split(v, 1)[1] if v in cmd_norm else ""
        if re.search(needs, tail, re.IGNORECASE):
            _block("READ-ONLY QA: %s in a writing form, with a protected repo in reach. "
                   "The read-only form of %s is still allowed." % (v, v))

    if re.search(INTERP, cmd_norm, re.IGNORECASE) and re.search(INTERP_WRITE, cmd, re.IGNORECASE):
        _block("READ-ONLY QA: interpreter write with a protected repo in reach. "
               "Write to the memory dir or qa-evidence instead.")

    if re.search(r"(?:^|[;&|])\s*(cd|pushd)\s", cmd_norm, re.IGNORECASE) and re.search(r">>?[^>]", cmd_norm):
        _block("READ-ONLY QA: redirect after a directory change into a protected repo is blocked.")

    if cwd and _in_src(cwd.replace(chr(92), "/")) and re.search(r">>?[^>]", cmd_norm):
        _block("READ-ONLY QA: redirect while the working directory is inside a protected repo is blocked.")


def main():
    cmd, cwd = _read_cmd()
    if not cmd:
        sys.exit(0)
    scan_git = strip_heredoc_bodies(cmd)                     # heredoc bodies are DATA for the git/npm scan
    scan_write = strip_heredoc_bodies(cmd, keep_interp=True)  # ...but a program fed to python/node is scanned for writes
    cmd_norm = scan_write.replace("\\", "/")
    if not owned_context(scan_git.replace("\\", "/"), cwd):
        check_git(scan_git)
        check_npm(scan_git)
    check_writes(cmd_norm)
    check_write_verb_near_src(scan_write, cmd_norm, cwd)
    check_cwd_and_interpreter_writes(scan_write, cmd_norm)
    sys.exit(0)


if __name__ == "__main__":
    main()
